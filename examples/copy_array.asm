; Копирование массива из 5 элементов с адресов 100–104 на адреса 200–204.
; Копия делается командой READ: mem[D] = mem[mem[C] + B],
; где в ячейке 10 лежит адрес начала массива (указатель), B — индекс.
; Вторая копия (адреса 300–304) делается командой WRITE: mem[C] = mem[B].
; Дамп для проверки: ./run.sh run output/copy_array.bin output/copy.csv 100-304

; 1. Исходный массив
LOAD 100, 11
LOAD 101, 22
LOAD 102, 33
LOAD 103, 44
LOAD 104, 55

; 2. Указатель на начало массива
LOAD 10, 100

; 3. Копия через READ (косвенная адресация со смещением)
READ 0, 10, 200
READ 1, 10, 201
READ 2, 10, 202
READ 3, 10, 203
READ 4, 10, 204

; 4. Копия через WRITE (прямая адресация)
WRITE 100, 300
WRITE 101, 301
WRITE 102, 302
WRITE 103, 303
WRITE 104, 304
