; Поэлементный sqrt() над вектором длины 10, результат — в исходный вектор.
; Данные: большие значения и граничные случаи (0, 1, максимум поля C).
; Вектор лежит по адресам 1000–1009, ячейка 0 — указатель на текущий элемент.
; Для каждого элемента: указатель = его адрес, затем SQRT элемент, указатель,
; то есть mem[1000+i] = sqrt(mem[1000+i]).
; Дамп: ./run.sh run output/vector_large.bin output/vector_large.csv 1000-1009

; Исходный вектор
LOAD 1000, 1048575
LOAD 1001, 1000000
LOAD 1002, 65536
LOAD 1003, 40000
LOAD 1004, 12345
LOAD 1005, 1024
LOAD 1006, 100
LOAD 1007, 50
LOAD 1008, 1
LOAD 1009, 0

; sqrt по каждому элементу на месте
LOAD 0, 1000
SQRT 1000, 0      ; sqrt(1048575) = 1023
LOAD 0, 1001
SQRT 1001, 0      ; sqrt(1000000) = 1000
LOAD 0, 1002
SQRT 1002, 0      ; sqrt(65536) = 256
LOAD 0, 1003
SQRT 1003, 0      ; sqrt(40000) = 200
LOAD 0, 1004
SQRT 1004, 0      ; sqrt(12345) = 111
LOAD 0, 1005
SQRT 1005, 0      ; sqrt(1024) = 32
LOAD 0, 1006
SQRT 1006, 0      ; sqrt(100) = 10
LOAD 0, 1007
SQRT 1007, 0      ; sqrt(50) = 7
LOAD 0, 1008
SQRT 1008, 0      ; sqrt(1) = 1
LOAD 0, 1009
SQRT 1009, 0      ; sqrt(0) = 0
