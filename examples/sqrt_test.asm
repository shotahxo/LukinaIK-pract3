; Проверка команды SQRT: mem[mem[C]] = sqrt(mem[B]).
; Корень целочисленный: берётся целая часть (sqrt(10) = 3).
; Аргументы лежат в ячейках 20–24, результаты пишутся в 40–44,
; адрес результата задаётся через ячейку-указатель 30.
; Дамп: ./run.sh run output/sqrt_test.bin output/sqrt.csv 20-44

; Аргументы
LOAD 20, 0
LOAD 21, 1
LOAD 22, 10
LOAD 23, 144
LOAD 24, 1000000

; Для каждого аргумента: указатель 30 = адрес результата, затем SQRT
LOAD 30, 40
SQRT 20, 30        ; mem[40] = sqrt(0)       = 0
LOAD 30, 41
SQRT 21, 30        ; mem[41] = sqrt(1)       = 1
LOAD 30, 42
SQRT 22, 30        ; mem[42] = sqrt(10)      = 3
LOAD 30, 43
SQRT 23, 30        ; mem[43] = sqrt(144)     = 12
LOAD 30, 44
SQRT 24, 30        ; mem[44] = sqrt(1000000) = 1000
